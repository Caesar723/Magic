from typing import TYPE_CHECKING
if TYPE_CHECKING:
    from game.player import Player

from game.card_simulation import bind_card,simulate,Card_Simulation
from pycards.sorcery.Frontier_Reinforcements.model import Frontier_Reinforcements


@bind_card(Frontier_Reinforcements)
class Frontier_Reinforcements_Simulation(Card_Simulation):

    similar_descriptions:list[str]=[
        "If you control no creatures, create two 1/2 green Scout creature tokens. Otherwise, create one 1/2 green Scout creature token.",
        "Create two 1/2 green Scout tokens if you have no creatures on the battlefield; otherwise create one.",
        "When you control no creatures, summon two green 1/2 Scouts. If you control any creatures, summon only one."
    ]

    @simulate
    def simulate_empty_battlefield(self):
        self.basic_initinal({
            "graveyard":{"creature_number":(0,0),"instant_number":(0,0),"sorcery_number":(0,0),"land_number":(0,0)},
            "hand":{"creature_number":(0,1),"instant_number":(0,1),"sorcery_number":(0,1),"land_number":(0,1)},
            "library":{"creature_number":(0,0),"instant_number":(0,0),"sorcery_number":(0,0),"land_number":(6,8)},
        })
        self.random_env_creature()(self.player)
        self.random_life()(self.player)
        self.random_env_creature()(self.player.opponent)
        self.random_life()(self.player.opponent)
        self.room.env_no_creature(self.player)
        self.room.env_mana(self.player,{"G":(1,4)},least_mana={"colorless":1,"G":1})
        return self.room.simulate_play(self.card,preferred_subactions=(0,))

    @simulate
    def simulate_occupied_battlefield(self):
        self.basic_initinal({
            "graveyard":{"creature_number":(0,0),"instant_number":(0,0),"sorcery_number":(0,0),"land_number":(0,0)},
            "hand":{"creature_number":(0,1),"instant_number":(0,1),"sorcery_number":(0,1),"land_number":(0,1)},
            "library":{"creature_number":(0,0),"instant_number":(0,0),"sorcery_number":(0,0),"land_number":(6,8)},
        })
        self.random_env_creature()(self.player)
        self.random_life()(self.player)
        self.random_env_creature()(self.player.opponent)
        self.random_life()(self.player.opponent)
        self.room.env_one_creature(self.player)
        self.room.env_mana(self.player,{"G":(1,4)},least_mana={"colorless":1,"G":1})
        return self.room.simulate_play(self.card,preferred_subactions=(0,))
